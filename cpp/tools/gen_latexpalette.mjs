// Generates core/latexpalette_data.cpp from app/src/renderer/latexpalette.ts (the data is the same; run again if the TS palette changes).
// Usage: node tools/gen_latexpalette.mjs   (from G:\xournal-lab\cpp; needs app/node_modules/esbuild)
import { createRequire } from "node:module";
import { writeFileSync, mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
const require = createRequire("G:/xournal-lab/app/package.json");
const esbuild = require("esbuild");
const out = join(mkdtempSync(join(tmpdir(), "pal-")), "pal.mjs");
esbuild.buildSync({ entryPoints: ["G:/xournal-lab/app/src/renderer/latexpalette.ts"], bundle: true, format: "esm", outfile: out });
const m = await import(pathToFileURL(out).href);
const lit = (s) => { // C++ raw string literal; the delimiter never occurs in TeX
  if (s.includes(')~"')) throw new Error("delimiter clash: " + s);
  return `R"~(${s})~"`;
};
let c = `// GENERATED by tools/gen_latexpalette.mjs from app/src/renderer/latexpalette.ts: do not edit by hand.
#include "latexpalette.h"

`;
c += `std::vector<PaletteCategory> buildPaletteCategories() {\n  std::vector<PaletteCategory> v;\n`;
for (const cat of m.PALETTE_CATEGORIES) {
  c += `  v.push_back({${lit(cat.id)}, QString::fromUtf8(${lit(cat.title)}), {\n`;
  for (const it of cat.items) c += `    {QString::fromUtf8(${lit(it.tex)}), QString::fromUtf8(${lit(it.snippet)}), QString::fromUtf8(${lit(it.name)})},\n`;
  c += `  }});\n`;
}
c += `  return v;
}
`;
writeFileSync("G:/xournal-lab/cpp/core/latexpalette_data.cpp", c);
console.log("items:", m.PALETTE_CATEGORIES.reduce((a, c) => a + c.items.length, 0));
